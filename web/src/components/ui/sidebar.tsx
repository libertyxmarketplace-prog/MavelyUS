const SIDEBAR_COOKIE_NAME = "sidebar_state"
const SIDEBAR_COOKIE_MAX_AGE = 60 * 60 * 24 * 7
const SIDEBAR_WIDTH = "16rem"
const SIDEBAR_WIDTH_MOBILE = "18rem"
const SIDEBAR_WIDTH_ICON = "3rem"
const SIDEBAR_KEYBOARD_SHORTCUT = "b"

type SidebarContextProps = {
  state: "expanded" | "collapsed"
  open: boolean
  setOpen: (open: boolean) => void
  openMobile: boolean
  setOpenMobile: (open: boolean) => void
  isMobile: boolean
  toggleSidebar: () => void
  /** True under a provider that frames a box on a page rather than the viewport. */
  contained: boolean
}

const SidebarContext = React.createContext<SidebarContextProps | null>(null)

function useSidebar() {
  const context = React.useContext(SidebarContext)
  if (!context) {
    return {
      state: "expanded" as const,
      open: true,
      setOpen: () => {},
      openMobile: false,
      setOpenMobile: () => {},
      isMobile: false,
      toggleSidebar: () => {},
      contained: false,
    }
  }

  return context
}

/** ⌘B on a Mac, Ctrl+B elsewhere: the chord that opens and closes the rail. */
function isToggleShortcut(event: { key: string; metaKey: boolean; ctrlKey: boolean }) {
  return event.key === SIDEBAR_KEYBOARD_SHORTCUT && (event.metaKey || event.ctrlKey)
}

function SidebarProvider({
  defaultOpen = true,
  open: openProp,
  onOpenChange: setOpenProp,
  contained = false,
  className,
  style,
  onKeyDown,
  children,
  ...props
}: React.ComponentProps<"div"> & {
  defaultOpen?: boolean
  open?: boolean
  onOpenChange?: (open: boolean) => void
  /**
   * Frames a box on a page instead of the viewport — a shell shown as one
   * band of a page, beside the page's own navigation. The desktop sidebar is
   * positioned in the box rather than fixed to the window, the inset is a
   * plain region rather than a second <main>, ⌘B / Ctrl+B toggles only while
   * focus is inside the box (its portalled sheet included), and the state is
   * never written to the sidebar_state cookie, which is the app's own shell's.
   * The box's height is the caller's to give, or its content's.
   */
  contained?: boolean
}) {
  const isMobile = useIsMobile()
  const [openMobile, setOpenMobile] = React.useState(false)

  // This is the internal state of the sidebar.
  // We use openProp and setOpenProp for control from outside the component.
  const [_open, _setOpen] = React.useState(defaultOpen)
  const open = openProp ?? _open
  const setOpen = React.useCallback(
    (value: boolean | ((value: boolean) => boolean)) => {
      const openState = typeof value === "function" ? value(open) : value
      if (setOpenProp) {
        setOpenProp(openState)
      } else {
        _setOpen(openState)
      }

      // This sets the cookie to keep the sidebar state. A contained sidebar
      // is a preview on some other page: its state is not the reader's
      // choice for the app's own rail, which reads this cookie.
      if (!contained) {
        document.cookie = `${SIDEBAR_COOKIE_NAME}=${openState}; path=/; max-age=${SIDEBAR_COOKIE_MAX_AGE}`
      }
    },
    [setOpenProp, open, contained]
  )

  // Helper to toggle the sidebar.
  const toggleSidebar = React.useCallback(() => {
    return isMobile ? setOpenMobile((open) => !open) : setOpen((open) => !open)
  }, [isMobile, setOpen, setOpenMobile])

  // Adds a keyboard shortcut to toggle the sidebar. A contained sidebar
  // listens on its own box instead (below), so the chord never reaches past it.
  React.useEffect(() => {
    if (contained) return
    const handleKeyDown = (event: KeyboardEvent) => {
      // A press already answered — by a contained box's own rail inside the
      // app, say — is not this rail's to toggle as well.
      if (event.defaultPrevented || !isToggleShortcut(event)) return
      event.preventDefault()
      toggleSidebar()
    }

    window.addEventListener("keydown", handleKeyDown)
    return () => window.removeEventListener("keydown", handleKeyDown)
  }, [toggleSidebar, contained])

  // We add a state so that we can do data-state="expanded" or "collapsed".
  // This makes it easier to style the sidebar with Tailwind classes.
  const state = open ? "expanded" : "collapsed"

  const contextValue = React.useMemo<SidebarContextProps>(
    () => ({
      state,
      open,
      setOpen,
      isMobile,
      openMobile,
      setOpenMobile,
      toggleSidebar,
      contained,
    }),
    [state, open, setOpen, isMobile, openMobile, setOpenMobile, toggleSidebar, contained]
  )

  return (
    <SidebarContext.Provider value={contextValue}>
      <div
        // data-slot is the caller's to rename (DashboardShell does);
        // data-sidebar marks the wrapper for the sidebar inside it.
        data-sidebar="wrapper"
        data-slot="sidebar-wrapper"
        data-contained={contained || undefined}
        style={
          {
            "--sidebar-width": SIDEBAR_WIDTH,
            "--sidebar-width-icon": SIDEBAR_WIDTH_ICON,
            ...style,
          } as React.CSSProperties
        }
        // A contained box takes focus from a click on its plain text, so the
        // chord answers anywhere in it, not only once a control has focus.
        tabIndex={contained ? -1 : undefined}
        // React bubbles a key press out of a portal along the component tree,
        // so the phone's sheet answers the chord here too.
        onKeyDown={
          contained
            ? (event) => {
                onKeyDown?.(event)
                if (event.defaultPrevented || !isToggleShortcut(event)) return
                event.preventDefault()
                toggleSidebar()
              }
            : onKeyDown
        }
        className={cn(
          "group/sidebar-wrapper flex w-full has-data-[variant=inset]:bg-sidebar",
          // The viewport's height in an app. A contained box is the edge the
          // sidebar is positioned against, it clips the rail's slide, and it is
          // a stacking context of its own: the rail's z-index and anything
          // sticky inside stay under a host page's sticky header.
          contained ? "relative isolate overflow-clip outline-none" : "min-h-svh",
          className
        )}
        {...props}
      >
        {children}
      </div>
    </SidebarContext.Provider>
  )
}

function Sidebar({
  side = "left",
  variant = "sidebar",
  collapsible = "offcanvas",
  sheetTitle = "Sidebar",
  className,
  children,
  dir,
  ...props
}: React.ComponentProps<"div"> & {
  side?: "left" | "right"
  variant?: "sidebar" | "floating" | "inset"
  collapsible?: "offcanvas" | "icon" | "none"
  /**
   * What the phone's sheet is called — the name of the dialog a screen reader
   * enters. AppSidebar names it for the product; every shell's was "Sidebar".
   */
  sheetTitle?: string
}) {
  const { isMobile, state, openMobile, setOpenMobile, contained } = useSidebar()
  const sidebarRef = React.useRef<HTMLDivElement>(null)

  // Slid off the canvas, the sidebar is out of reach: inert and hidden from
  // assistive technology, so nothing in it takes focus or is read out — it is
  // gone from view, and a tab stop in it would land on nothing to see. Focus
  // caught in it as it goes moves on first, to the toggle that brings it back
  // (or to a contained box itself): a browser drops focus from an inert
  // element at once, to the top of the page. So the attributes are set here,
  // after that move, rather than rendered — the first render carries them,
  // for the server's HTML, and nothing re-renders them after.
  const folded = state === "collapsed" && collapsible === "offcanvas"
  const [foldedAtFirst] = React.useState(folded)
  React.useLayoutEffect(() => {
    const sidebar = sidebarRef.current
    if (!sidebar) return
    if (folded && sidebar.contains(document.activeElement)) {
      const wrapper = sidebar.closest<HTMLElement>("[data-sidebar=wrapper]")
      const toggles = [...(wrapper?.querySelectorAll<HTMLElement>("[data-sidebar=trigger]") ?? [])]
      ;(toggles.find((toggle) => !sidebar.contains(toggle)) ?? wrapper)?.focus()
    }
    sidebar.toggleAttribute("inert", folded)
    if (folded) sidebar.setAttribute("aria-hidden", "true")
    else sidebar.removeAttribute("aria-hidden")
  }, [folded, isMobile])

  if (collapsible === "none") {
    return (
      <div
        data-slot="sidebar"
        className={cn(
          "flex h-full w-(--sidebar-width) flex-col bg-sidebar text-sidebar-foreground",
          className
        )}
        {...props}
      >
        {children}
      </div>
    )
  }

  if (isMobile) {
    return (
      <Sheet open={openMobile} onOpenChange={setOpenMobile} {...props}>
        <SheetContent
          dir={dir}
          data-sidebar="sidebar"
          data-slot="sidebar"
          data-mobile="true"
          className="w-(--sidebar-width) bg-sidebar p-0 text-sidebar-foreground [&>button]:hidden"
          style={
            {
              "--sidebar-width": SIDEBAR_WIDTH_MOBILE,
            } as React.CSSProperties
          }
          side={side}
        >
          <SheetHeader className="sr-only">
            <SheetTitle>{sheetTitle}</SheetTitle>
            <SheetDescription>Displays the mobile sidebar.</SheetDescription>
          </SheetHeader>
          <div className="flex h-full w-full flex-col">{children}</div>
        </SheetContent>
      </Sheet>
    )
  }

  return (
    <div
      ref={sidebarRef}
      className="group peer hidden text-sidebar-foreground md:block"
      inert={foldedAtFirst}
      aria-hidden={foldedAtFirst || undefined}
      data-state={state}
      data-collapsible={state === "collapsed" ? collapsible : ""}
      data-variant={variant}
      data-side={side}
      data-slot="sidebar"
    >
      {/* This is what handles the sidebar gap on desktop */}
      <div
        data-slot="sidebar-gap"
        className={cn(
          "relative w-(--sidebar-width) bg-transparent transition-[width] duration-(--duration-base) ease-(--ease-emphasized)",
          "group-data-[collapsible=offcanvas]:w-0",
          "group-data-[side=right]:rotate-180",
          variant === "floating" || variant === "inset"
            ? "group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+(--spacing(4)))]"
            : "group-data-[collapsible=icon]:w-(--sidebar-width-icon)"
        )}
      />
      <div
        data-slot="sidebar-container"
        data-side={side}
        className={cn(
          "inset-y-0 z-10 hidden w-(--sidebar-width) transition-[left,right,width] duration-(--duration-base) ease-(--ease-emphasized) data-[side=left]:left-0 data-[side=left]:group-data-[collapsible=offcanvas]:left-[calc(var(--sidebar-width)*-1)] data-[side=right]:right-0 data-[side=right]:group-data-[collapsible=offcanvas]:right-[calc(var(--sidebar-width)*-1)] md:flex",
          // Fixed to the window's edge in an app; a contained provider's box
          // is the edge, so the sidebar is placed in it, as tall as it is.
          contained ? "absolute h-full" : "fixed h-svh",
          // Adjust the padding for floating and inset variants.
          variant === "floating" || variant === "inset"
            ? "p-2 group-data-[collapsible=icon]:w-[calc(var(--sidebar-width-icon)+(--spacing(4))+2px)]"
            : "group-data-[collapsible=icon]:w-(--sidebar-width-icon) group-data-[side=left]:border-r group-data-[side=right]:border-l",
          className
        )}
        {...props}
      >
        <div
          data-sidebar="sidebar"
          data-slot="sidebar-inner"
          className="flex size-full flex-col bg-sidebar group-data-[variant=floating]:rounded-lg group-data-[variant=floating]:shadow-sm group-data-[variant=floating]:ring-1 group-data-[variant=floating]:ring-sidebar-border"
        >
          {children}
        </div>
      </div>
    </div>
  )
}

function SidebarTrigger({
  className,
  onClick,
  ...props
}: React.ComponentProps<typeof Button>) {
  const { toggleSidebar, open, openMobile, isMobile } = useSidebar()

  return (
    <Button
      data-sidebar="trigger"
      data-slot="sidebar-trigger"
      variant="ghost"
      size="icon-sm"
      // Says which way the next press goes: whether the rail is expanded, or
      // on a phone whether its sheet is showing.
      aria-expanded={isMobile ? openMobile : open}
      className={cn(className)}
      onClick={(event) => {
        onClick?.(event)
        toggleSidebar()
      }}
      {...props}
    >
      <PanelLeftIcon />
      <span className="sr-only">Toggle Sidebar</span>
    </Button>
  )
}

